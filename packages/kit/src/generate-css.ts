import {
  breakpointConditions,
  freeProps,
  stateConditions,
  tokenProps,
  type Condition,
} from "./box/props.ts";
import { conditionClass, freeVariable } from "./box/resolve.ts";
import {
  breakpoints,
  colors,
  durations,
  easings,
  fontSizes,
  fontWeights,
  lineHeights,
  palette,
  radii,
  shadows,
  spacing,
  tailwindText,
  tailwindWeights,
  textColors,
  textRoles,
} from "./tokens.ts";

const NOTICE = "/* Generated by `bun run generate`. Edit src/tokens.ts or src/box/props.ts. */\n";

function variables(prefix: string, values: Record<string, string>) {
  return Object.entries(values).map(([name, value]) => `  --ag-${prefix}${name}: ${value};`);
}

export function generateTokensCss() {
  const colorPairs = Object.entries(colors).map(
    ([name, [light, dark]]) => `  --ag-${name}: light-dark(var(--ag-${light}), var(--ag-${dark}));`,
  );

  const lines = [
    ...variables("", palette),
    ...colorPairs,
    ...variables("space-", spacing),
    ...variables("radius-", radii),
    ...variables("shadow-", shadows),
    ...variables("duration-", durations),
    ...variables("ease-", easings),
    ...variables("font-size-", fontSizes),
    ...variables("leading-", lineHeights),
    ...variables("weight-", fontWeights),
  ];

  const tailwind = [
    ...Object.entries(tailwindText).flatMap(([name, { size, leading }]) => [
      `  --text-${name}: ${fontSizes[size]};`,
      `  --text-${name}--line-height: ${lineHeights[leading]};`,
    ]),
    ...Object.entries(tailwindWeights).map(
      ([name, weight]) => `  --font-weight-${name}: ${fontWeights[weight]};`,
    ),
    "  --tracking-tight: 0em;",
  ];

  return `${NOTICE}:root,\n:host {\n${lines.join("\n")}\n}\n\n@theme {\n${tailwind.join("\n")}\n}\n`;
}

function selector(condition: Condition, name: string) {
  const className = conditionClass(condition, name).replace(":", "\\:");
  const state =
    condition in stateConditions ? stateConditions[condition as keyof typeof stateConditions] : "";
  return `.${className}${state}`;
}

interface Rule {
  name: string;
  declaration: (condition: Condition) => string;
  states: boolean;
}

function boxRules(): Rule[] {
  const tokens = Object.values(tokenProps).flatMap((prop) =>
    Object.entries(prop.values).map(([token, value]) => ({
      name: `${prop.slug}-${token}`,
      declaration: () => `${prop.css}: ${String(value)}`,
      states: "states" in prop,
    })),
  );

  const free = Object.values(freeProps).map((prop) => ({
    name: prop.slug,
    declaration: (condition: Condition) =>
      `${prop.css}: var(${freeVariable(prop.slug, condition)})`,
    states: "states" in prop,
  }));

  return [...tokens, ...free];
}

function textRules() {
  const roles = Object.entries(textRoles).flatMap(([name, role]) => {
    const weight = "weight" in role ? ` font-weight: var(--ag-weight-${role.weight});` : "";
    const base = `.ag-role-${name} { font-size: var(--ag-font-size-${role.size}); line-height: var(--ag-leading-${role.leading});${weight} }`;
    return "mdSize" in role
      ? [
          base,
          `@media (min-width: ${breakpoints.md}) { .ag-role-${name} { font-size: var(--ag-font-size-${role.mdSize}); } }`,
        ]
      : [base];
  });

  const tones = Object.entries(textColors).map(
    ([name, token]) => `.ag-tone-${name} { color: var(--ag-${token}); }`,
  );
  const weights = Object.keys(fontWeights).map(
    (name) => `.ag-weight-${name} { font-weight: var(--ag-weight-${name}); }`,
  );

  return [
    ...roles,
    ...tones,
    ...weights,
    ...["left", "center", "right"].map((value) => `.ag-align-${value} { text-align: ${value}; }`),
    ...["wrap", "nowrap", "balance", "pretty"].map(
      (value) => `.ag-wrap-${value} { text-wrap: ${value}; }`,
    ),
    ".ag-mono { font-family: var(--font-mono); }",
    ".ag-tabular { font-variant-numeric: tabular-nums; }",
    ".ag-line-through { text-decoration: line-through; }",
    ".ag-truncate { overflow: hidden; text-overflow: ellipsis; white-space: nowrap; }",
    ".ag-clamp { display: -webkit-box; overflow: hidden; -webkit-box-orient: vertical; -webkit-line-clamp: var(--ag-lines); }",
  ];
}

export function generateBoxCss() {
  const rules = boxRules();
  const rule = (condition: Condition, item: Rule) =>
    `${selector(condition, item.name)} { ${item.declaration(condition)}; }`;

  const base = rules.map((item) => rule("base", item));

  const responsive = breakpointConditions.map((condition) => {
    const body = rules.map((item) => `  ${rule(condition, item)}`).join("\n");
    return `@media (min-width: ${breakpoints[condition]}) {\n${body}\n}`;
  });

  const interactive = rules.filter((item) => item.states);
  const states = (Object.keys(stateConditions) as (keyof typeof stateConditions)[]).map(
    (condition) => {
      const body = interactive.map((item) => rule(condition, item));
      return condition === "hover"
        ? `@media (hover: hover) {\n${body.map((line) => `  ${line}`).join("\n")}\n}`
        : body.join("\n");
    },
  );

  return `${NOTICE}${[...base, ...textRules(), ...responsive, ...states].join("\n")}\n`;
}
